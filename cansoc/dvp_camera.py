"""
dvp_camera.py -- OV2640 (DVP) greyscale strip capture for the Tang Nano 4K LiteX SoC.

Sensor side is Sipeed's working camera_hdmi demo (TangNano-4K-example): its SCCB controller
and register table, unchanged except for the output size and output format, which are patched
at build time.

    sys clk --/xclk_div--> XCLK --------------------------------------> OV2640
    sys clk -------------> OV2640_Controller (Sipeed Verilog, SCCB) --> SCL/SDA
    PCLK/HREF/VSYNC/D[9:2] --> capture FSM (pix domain) --> strip buffer (BSRAM) --CSR--> M3

Why strips
----------
The sensor delivers width x height pixels per frame; nothing on this board can hold a frame
(800x600 = 469 KB). The buffer holds `rows` lines (800 x 10 = 8000 B = 4 BSRAM, the same 4 the
earlier 96x72 frame buffer used). The M3 sets row_start, arms, and the FSM stores lines
row_start .. row_start+rows-1 of the next frame. Stepping row_start through the frame and
sending each strip builds the full image over height/rows frames.

Greyscale
---------
fmt="yuv"  : sensor outputs YUV422 (2 bytes per pixel, Y U Y V ...). The FSM keeps one byte
             of each pair; which one is ctrl/y_phase (runtime bit, so a wrong guess of the
             byte order is fixed without a rebuild).
fmt="raw"  : the demo's RAW10, D[9:2] kept (Bayer pattern visible as a fine checker).

Registers (CSR)
---------------
ctrl.arm      pulse: capture the strip at row_start from the next frame
ctrl.resend   pulse: re-run the SCCB init table
ctrl.y_phase  0/1: which byte of each YUV pair is Y (ignored for raw)
row_start     first frame line to store
status.done   strip is in the buffer (stays until the next arm)
status.cfg_done SCCB table finished
rd_addr/rd_data  word index (y*width/4 + x/4) / 4 pixels, byte 0 = leftmost
dbg_frames / dbg_line_len / dbg_lines   free-running sensor health counters
                                        (line_len counts PCLKs per HREF: 2*width in yuv)
"""

import os
import re

from migen import *
from migen.genlib.cdc import MultiReg, PulseSynchronizer

from litex.gen import LiteXModule
from litex.soc.interconnect.csr import CSRStorage, CSRStatus, CSRField

RTL_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "ov2640")

# OV2640 DSP bank register 0xDA (IMAGE_MODE) output format.
IMAGE_MODE = {"yuv": 0x00, "raw": 0x04}


def patched_register_file(width, height, fmt, out_dir):
    """Copy Sipeed's OV2640_Registers.v with output size and format patched."""
    assert width % 4 == 0 and height % 4 == 0, "OV2640 output size must be a multiple of 4"
    assert width <= 800 and height <= 600, "the demo's sensor window is SVGA (800x600)"
    src = open(os.path.join(RTL_DIR, "OV2640_Registers.v")).read()

    # The register LUT is the first `case` block; a second, commented-out copy follows it.
    end = src.index("default :")
    head, tail = src[:end], src[end:]

    zmow, zmoh = width >> 2, height >> 2
    zmhh = ((zmoh >> 6) & 0x04) | ((zmow >> 8) & 0x03)   # 0x5C = {ZMOH[8], ZMOW[9:8]}
    for reg, val in [("5A", zmow & 0xFF), ("5B", zmoh & 0xFF), ("5C", zmhh)]:
        head, k = re.subn(r"(16'h{}_)[0-9A-Fa-f]{{2}}(;)".format(reg),
                          r"\g<1>{:02X}\2".format(val), head, count=1)
        assert k == 1, "register 0x{} not found in OV2640_Registers.v".format(reg)
    head, k = re.subn(r"(16'hDA_)[0-9A-Fa-f]{2}(;)",
                      r"\g<1>{:02X}\2".format(IMAGE_MODE[fmt]), head)
    assert k >= 1, "register 0xDA not found in OV2640_Registers.v"

    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "OV2640_Registers_{}x{}_{}.v".format(width, height, fmt))
    with open(dst, "w") as f:
        f.write(head + tail)
    return dst


FB_VERILOG = """\
// cam_fb.v -- simple dual-port strip buffer (generated by cansoc/dvp_camera.py)
// One write port (PCLK), one registered read port (sys) -> Gowin infers SDPB BSRAM.
module cam_fb #(parameter AW = 11, parameter DEPTH = 2000) (
    input  wire          wclk,
    input  wire          we,
    input  wire [AW-1:0] waddr,
    input  wire [31:0]   wdata,
    input  wire          rclk,
    input  wire [AW-1:0] raddr,
    output reg  [31:0]   rdata
);
    reg [31:0] mem [0:DEPTH-1] /* synthesis syn_ramstyle = "block_ram" */;
    always @(posedge wclk) if (we) mem[waddr] <= wdata;
    always @(posedge rclk) rdata <= mem[raddr];
endmodule
"""


def write_fb_module(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "cam_fb.v")
    with open(dst, "w") as f:
        f.write(FB_VERILOG)
    return dst


class DVPCamera(LiteXModule):
    def __init__(self, platform, pads, width=800, height=600, rows=10, fmt="yuv",
                 sys_clk_freq=54e6, xclk_freq=13.5e6, gateware_dir="build/ov2640"):
        assert fmt in IMAGE_MODE
        assert width % 4 == 0
        assert height % rows == 0, "rows must divide height"
        self.width, self.height, self.rows, self.fmt = width, height, rows, fmt
        words = width * rows // 4

        # CSRs -------------------------------------------------------------------------------------
        self.ctrl = CSRStorage(fields=[
            CSRField("arm",     size=1, offset=0, pulse=True, description="Capture one strip."),
            CSRField("resend",  size=1, offset=1, pulse=True, description="Re-run the SCCB table."),
            CSRField("y_phase", size=1, offset=2, description="YUV: which byte of a pair is Y."),
        ])
        self.row_start = CSRStorage(bits_for(height), description="First frame line of the strip.")
        self.status = CSRStatus(fields=[
            CSRField("done",     size=1, offset=0, description="Strip captured, buffer valid."),
            CSRField("cfg_done", size=1, offset=1, description="SCCB init table finished."),
        ])
        self.rd_addr      = CSRStorage(bits_for(words - 1), description="Strip buffer word index.")
        self.rd_data      = CSRStatus(32, description="4 pixels at rd_addr, byte 0 = leftmost.")
        self.dbg_frames   = CSRStatus(16)
        self.dbg_line_len = CSRStatus(16)
        self.dbg_lines    = CSRStatus(16)

        # XCLK = sys / xclk_div (even divider -> 50 % duty) -----------------------------------------
        # OV2640 accepts ~6..27 MHz; 13.5 MHz is what this design was proven with.
        xclk_div = int(round(sys_clk_freq / xclk_freq))
        assert xclk_div >= 2 and xclk_div % 2 == 0, "xclk_div must be even"
        xclk     = Signal()
        xclk_cnt = Signal(max=xclk_div // 2)
        self.sync += If(xclk_cnt == xclk_div // 2 - 1,
            xclk_cnt.eq(0), xclk.eq(~xclk),
        ).Else(
            xclk_cnt.eq(xclk_cnt + 1),
        )
        self.comb += pads.xclk.eq(xclk)

        # SCCB init: Sipeed's controller + LUT, clocked from sys -----------------------------------
        # (one SCCB bit per 256 clocks: ~211 kHz at 54 MHz, below the 400 kHz limit)
        cfg_done = Signal()
        self.specials += Instance("OV2640_Controller",
            i_clk             = ClockSignal("sys"),
            i_resend          = self.ctrl.fields.resend,
            o_config_finished = cfg_done,
            o_sioc            = pads.scl,
            io_siod           = pads.sda,
            o_reset           = Signal(),
            o_pwdn            = Signal(),
        )
        platform.add_source(os.path.join(RTL_DIR, "OV2640_Controller.v"))
        platform.add_source(os.path.join(RTL_DIR, "I2C_Interface.v"))
        platform.add_source(patched_register_file(width, height, fmt, gateware_dir))

        # Pixel clock domain ------------------------------------------------------------------------
        self.cd_pix = ClockDomain(reset_less=True)
        self.comb += self.cd_pix.clk.eq(pads.pclk)
        platform.add_period_constraint(pads.pclk, 1e9/50e6)

        # Strip buffer: written at PCLK, read by the CPU at sys -------------------------------------
        aw = bits_for(words - 1)
        wp = self._wp = Record([("adr", aw), ("dat_w", 32), ("we", 1)])
        fb_rdata = Signal(32)
        self.specials += Instance("cam_fb",
            p_AW    = aw,
            p_DEPTH = words,
            i_wclk  = ClockSignal("pix"),
            i_we    = wp.we,
            i_waddr = wp.adr,
            i_wdata = wp.dat_w,
            i_rclk  = ClockSignal("sys"),
            i_raddr = self.rd_addr.storage,
            o_rdata = fb_rdata,
        )
        platform.add_source(write_fb_module(gateware_dir))
        self.comb += self.rd_data.status.eq(fb_rdata)

        # Input registers (pix) ----------------------------------------------------------------------
        # D[9:0] as one bus, or data_lo (D0-D7) + data_hi (D8-D9) when they sit in banks with
        # different VCCIO (Tang Nano 4K: bank 3 = 1.8 V, bank 1 = 3.3 V).
        data = pads.data if hasattr(pads, "data") else Cat(pads.data_lo, pads.data_hi)
        d      = Signal(8)
        href   = Signal()
        href_d = Signal()
        vs     = Signal()
        vs_d   = Signal()
        self.sync.pix += [
            d.eq(data[2:10]),        # D[9:2]: 8-bit YUV byte, or RAW10 >> 2
            href.eq(pads.href),
            href_d.eq(href),
            vs.eq(pads.vsync),
            vs_d.eq(vs),
        ]
        vs_edge  = Signal()
        vs_rise  = Signal()
        line_end = Signal()
        self.comb += [
            vs_edge.eq(vs ^ vs_d),
            vs_rise.eq(vs & ~vs_d),
            line_end.eq(href_d & ~href),
        ]

        # Byte select: in YUV keep one byte of each pair (phase restarts every line) -----------------
        y_phase = Signal()
        self.specials += MultiReg(self.ctrl.fields.y_phase, y_phase, "pix")
        byte_ph = Signal()
        take    = Signal()
        self.sync.pix += If(href, byte_ph.eq(~byte_ph)).Else(byte_ph.eq(0))
        if fmt == "yuv":
            self.comb += take.eq(href & (byte_ph == y_phase))
        else:
            self.comb += take.eq(href)

        # sys -> pix: arm pulse and row_start (quasi-static: written before arm) ----------------------
        self.arm_ps = arm_ps = PulseSynchronizer("sys", "pix")
        self.comb  += arm_ps.i.eq(self.ctrl.fields.arm)
        row_start = Signal(bits_for(height))
        self.specials += MultiReg(self.row_start.storage, row_start, "pix")

        # pix -> sys: done / cfg_done -----------------------------------------------------------------
        done_pix = Signal()
        self.specials += [
            MultiReg(done_pix, self.status.fields.done),
            MultiReg(cfg_done, self.status.fields.cfg_done),
        ]

        # Capture FSM (pix) --------------------------------------------------------------------------
        # armed -> wait for a VSYNC edge (either polarity: both edges are in vertical blanking)
        # capturing -> count lines; store lines row_start .. row_start+rows-1, first `width` pixels.
        armed     = Signal()
        capturing = Signal()
        line      = Signal(bits_for(height + rows))   # frame line counter
        x         = Signal(bits_for(width))           # pixels kept in this line
        y         = Signal(max=rows)                  # row inside the strip
        in_strip  = Signal()
        shift     = Signal(24)
        self.comb += [
            in_strip.eq((line >= row_start) & (line < row_start + rows)),
            y.eq(line - row_start),
            wp.adr.eq(y * (width // 4) + x[2:]),
            wp.dat_w.eq(Cat(shift, d)),               # 3 older pixels + this one, leftmost = byte 0
            wp.we.eq(capturing & in_strip & take & (x < width) & (x[0:2] == 3)),
        ]
        self.sync.pix += [
            If(arm_ps.o,
                armed.eq(1), capturing.eq(0), done_pix.eq(0),
            ).Elif(armed & vs_edge,
                armed.eq(0), capturing.eq(1), line.eq(0), x.eq(0),
            ).Elif(capturing,
                If(take,
                    If(x != width, x.eq(x + 1)),
                    shift.eq(Cat(shift[8:], d)),
                ),
                If(line_end,
                    x.eq(0),
                    If(line == row_start + rows - 1,
                        capturing.eq(0), done_pix.eq(1),
                    ).Else(
                        line.eq(line + 1),
                    ),
                ),
            ),
        ]

        # Debug counters (pix, free-running) ---------------------------------------------------------
        frames   = Signal(16)
        lines    = Signal(16)
        line_len = Signal(16)
        last_len = Signal(16)
        last_ln  = Signal(16)
        self.sync.pix += [
            If(href, line_len.eq(line_len + 1)),
            If(line_end, last_len.eq(line_len), line_len.eq(0), lines.eq(lines + 1)),
            If(vs_rise, frames.eq(frames + 1), last_ln.eq(lines), lines.eq(0)),
        ]
        self.specials += [
            MultiReg(frames,   self.dbg_frames.status),
            MultiReg(last_len, self.dbg_line_len.status),
            MultiReg(last_ln,  self.dbg_lines.status),
        ]
