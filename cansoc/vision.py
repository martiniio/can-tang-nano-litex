class Vision(LiteXModule):
    """Watch + Snitch on the same pixel stream (broadcast: both see every pixel)."""
    def __init__(self, platform, sink, width=800, height=600,
                 gateware_dir="build/vision", sim=False):
        self.watch  = Watch(platform, sink, width, height, gateware_dir, sim)
        self.snitch = Snitch(platform, sink, width, height, gateware_dir, sim)
 
        # Sizes the firmware / receivers need; the SoC publishes them in soc.h.
        self.constants = {
            "VIS_WIDTH":               width,
            "VIS_HEIGHT":              height,
            "VIS_SNITCH_SLOTS":        N_SLOTS,
            "VIS_SNITCH_PACKET_WORDS": width // 4 + 3,
            "VIS_WATCH_TILE":          WATCH_TILE,
            "VIS_WATCH_TILES_X":       width // WATCH_TILE,
            "VIS_WATCH_TILES_Y":       height // WATCH_TILE,
            "VIS_WATCH_STEP":          WATCH_STEP,
            "VIS_WATCH_THRESH":        WATCH_THRESH,
            "VIS_WATCH_OFF_DELAY":     WATCH_OFF_DELAY,
        }
 
