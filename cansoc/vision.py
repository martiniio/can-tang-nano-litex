
import os
 
from migen import *
 
from litex.gen import LiteXModule
from litex.soc.interconnect.csr import CSRStorage, CSRStatus, CSRField
 
N_SLOTS = 7
 
# Watch: Frigate defaults, mapped to our tiles (docs/watch_frigate.md) ------------------------------
WATCH_TILE        = 50     # tile size (px): 16 x 12 tiles at 800 x 600
WATCH_STEP        = 7      # use every 7th frame: 34 / 7 = 4.9 fps     (Frigate detect fps 5)
WATCH_THRESH      = 15     # tile mean difference counted as change    (Frigate threshold 30 per pixel)
WATCH_MIN_TILES   = 1      # changed tiles for a motion frame          (Frigate contour_area 10)
WATCH_LIGHT_PCT   = 80     # % changed -> calibrating                  (Frigate lightning_threshold 0.8)
WATCH_CAL_EXIT    = 5      # % changed below which calibrating ends    (Frigate pct_motion < 0.05)
WATCH_ALPHA       = 7      # background alpha 1/128                    (Frigate frame_alpha 0.01)
WATCH_ALPHA_CAL   = 2      # background alpha 1/4 while calibrating    (Frigate 0.2)
WATCH_LEARN_AFTER = 10     # motion frames before they are learned     (Frigate motion_frame_count >= 10)
WATCH_OFF_DELAY   = 150    # detect frames without motion -> episode ends (Frigate mqtt_off_delay 30 s)
 
 
# Simple dual-port RAM (one write port, one registered read port, one clock) ---------------------
 
SDP_RAM_VERILOG = """\
// vis_sdp_ram.v -- simple dual-port block RAM (generated by cansoc/vision.py)
module vis_sdp_ram #(parameter W = 32, parameter AW = 11, parameter DEPTH = 2030) (
    input  wire          clk,
    input  wire          we,
    input  wire [AW-1:0] waddr,
    input  wire [W-1:0]  wdata,
    input  wire [AW-1:0] raddr,
    output reg  [W-1:0]  rdata
);
    reg [W-1:0] mem [0:DEPTH-1] /* synthesis syn_ramstyle = "block_ram" */;
    always @(posedge clk) begin
        if (we) mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end
endmodule
"""
 
 
class _SDPRam(Module):
    """we/waddr/wdata in, raddr in, rdata = mem[raddr] one clock later."""
    def __init__(self, platform, width, depth, gateware_dir, sim):
        aw = bits_for(depth - 1)
        self.we    = Signal()
        self.waddr = Signal(aw)
        self.wdata = Signal(width)
        self.raddr = Signal(aw)
        self.rdata = Signal(width)
        if sim:
            mem = Memory(width, depth)
            wp  = mem.get_port(write_capable=True)
            rp  = mem.get_port()
            self.specials += mem, wp, rp
            self.comb += [
                wp.we.eq(self.we), wp.adr.eq(self.waddr), wp.dat_w.eq(self.wdata),
                rp.adr.eq(self.raddr), self.rdata.eq(rp.dat_r),
            ]
        else:
            self.specials += Instance("vis_sdp_ram",
                p_W = width, p_AW = aw, p_DEPTH = depth,
                i_clk   = ClockSignal("sys"),
                i_we    = self.we,
                i_waddr = self.waddr,
                i_wdata = self.wdata,
                i_raddr = self.raddr,
                o_rdata = self.rdata,
            )
            os.makedirs(gateware_dir, exist_ok=True)
            path = os.path.join(gateware_dir, "vis_sdp_ram.v")
            with open(path, "w") as f:
                f.write(SDP_RAM_VERILOG)
            platform.add_source(path)
 
 
def crc16_ccitt_byte(crc, byte):
    """CRC-16/CCITT-FALSE, one byte, MSB first, as a Migen expression (8 unrolled bit steps)."""
    c = [crc[i] for i in range(16)]
    for i in reversed(range(8)):
        fb = c[15] ^ byte[i]
        c  = [fb] + c[:15]                                   # shift left, bit 0 <- feedback
        c  = [c[k] ^ fb if (0x1021 >> k) & 1 and k != 0 else c[k] for k in range(16)]
    return Cat(*c)
 
 
# Watch ---------------------------------------------------------------------------------------------
 
class Watch(LiteXModule):
    """Motion detection after Frigate, one event per episode. (CSR: vis_watch_*)"""
    def __init__(self, platform, sink, width, height, gateware_dir, sim=False):
        T  = WATCH_TILE
        assert width % T == 0 and height % T == 0
        nx, ny = width // T, height // T                 # 16 x 12
        n_tiles = nx * ny                                # 192
        light   = n_tiles * WATCH_LIGHT_PCT // 100       # 153
        cal_out = (n_tiles * WATCH_CAL_EXIT + 99) // 100 # 10
        self.geometry = (nx, ny)
 
        # Registers ---------------------------------------------------------------------------------
        self.ctrl = CSRStorage(fields=[
            CSRField("start", size=1, offset=0, pulse=True, description="Begin watching (calibrates first)."),
            CSRField("stop",  size=1, offset=1, pulse=True, description="Stop watching."),
        ])
        self.status = CSRStatus(fields=[
            CSRField("running",     size=1, offset=0),
            CSRField("calibrating", size=1, offset=1),
            CSRField("active",      size=1, offset=2, description="Inside a motion episode."),
            CSRField("ready",       size=1, offset=3, description="An event is waiting."),
            CSRField("lost",        size=4, offset=4, description="Events overwritten before read."),
            CSRField("changed",     size=8, offset=8, description="Changed tiles, last detect frame."),
        ])
        self.event0 = CSRStatus(32, description="Event: frame (15:0), tiles (23:16).")
        self.event1 = CSRStatus(16, description="Event bbox: x0, x1, y0, y1 (4 bit each); read takes it.")
        self.frame  = CSRStatus(16, description="frame_id of the last frame seen.")
 
        start = self.ctrl.fields.start
        stop  = self.ctrl.fields.stop
        self.sync += If(sink.valid & sink.eof, self.frame.status.eq(sink.frame_id))
 
        # Tile state in BSRAM: {B (8.8 fixed point, 16 bit), m (last mean, 8 bit)} per tile --------
        self.ram = ram = _SDPRam(platform, 24, n_tiles, gateware_dir, sim)
 
        running     = Signal()
        calibrating = Signal()
        use         = Signal()                  # this frame is a detect frame
        step        = Signal(max=max(WATCH_STEP, 2))
        fid         = Signal(16)                # frame_id of the detect frame
 
        # Pick every STEP-th frame ------------------------------------------------------------------
        sof = sink.valid & sink.sof
        self.sync += If(sof,
            step.eq(Mux(step == WATCH_STEP - 1, 0, step + 1)),
            use.eq(running & (step == WATCH_STEP - 1)),
            fid.eq(sink.frame_id),
        )
 
        # Per pixel: sums[tx] += pix (16 running sums, one per tile of the current band) ------------
        sum_w  = bits_for(T * T * 255)          # 20 bit for 50 x 50
        sums   = Array(Signal(sum_w, name="wsum{}".format(i)) for i in range(nx))
        cx     = Signal(max=T)                  # pixel position inside the tile
        tx     = Signal(max=nx)                 # tile column of the next pixel
        cur_cx = Signal(max=T)
        cur_tx = Signal(max=nx)
        self.comb += [
            cur_cx.eq(Mux(sink.x == 0, 0, cx)),
            cur_tx.eq(Mux(sink.x == 0, 0, tx)),
        ]
        clr     = Signal()                      # clear sums[k] (band pass, phase 3)
        k       = Signal(max=n_tiles + 1)       # tile index of the pass
        add_sum = Signal(sum_w)
        self.comb += add_sum.eq(sums[cur_tx] + sink.pix)
        for i in range(nx):
            self.sync += If(clr & (k == i),
                sums[i].eq(0),
            ).Elif(sink.valid & use & (cur_tx == i),
                sums[i].eq(add_sum),
            )
        self.sync += If(sink.valid,
            If(cur_cx == T - 1, cx.eq(0), tx.eq(cur_tx + 1)).Else(cx.eq(cur_cx + 1), tx.eq(cur_tx)),
        )
 
        # Per row: band position; a band ends after T rows ------------------------------------------
        ry        = Signal(max=T)
        band      = Signal(max=ny + 1)
        pass_band = Signal(max=ny)              # band whose tiles the pass works on
        band_end = Signal()                     # pulse: rows of `band` complete
        last     = Signal()                     # ...and it is the last band of the frame
        self.sync += [
            band_end.eq(0),
            If(sof, ry.eq(0), band.eq(0)),
            If(sink.valid & sink.eol & ~sof,
                If(ry == T - 1,
                    ry.eq(0),
                    band_end.eq(use),
                    last.eq(sink.eof),
                    pass_band.eq(band),
                    band.eq(band + 1),
                ).Else(
                    ry.eq(ry + 1),
                ),
            ),
        ]
 
        # Sequencer: BAND (nx tiles) -> [last band] DECIDE -> UPDATE (all tiles) --------------------
        n_chg   = Signal(max=n_tiles + 1)
        x0 = Signal(4); x1 = Signal(4); y0 = Signal(4); y1 = Signal(4)
        upd     = Signal()                      # learn this frame
        a_shift = Signal(3)
        motion_cnt = Signal(max=WATCH_LEARN_AFTER + 1)
        active  = Signal()
        off_cnt = Signal(max=WATCH_OFF_DELAY + 1)
        ready   = Signal()
        lost    = Signal(4)
        ev_fid  = Signal(16); ev_n = Signal(8)
        ev_x0 = Signal(4); ev_x1 = Signal(4); ev_y0 = Signal(4); ev_y1 = Signal(4)
 
        # tile mean m = sum / T^2 ~= (sum * mul) >> 18 (T = 50: mul = 105), clamped (no divider)
        mul   = round((1 << 18) / (T * T))
        s_r   = Signal(sum_w)                   # sums[k], registered      (phase 1)
        prod  = Signal(sum_w + bits_for(mul))
        m_raw = Signal(len(prod) - 18)
        m_r   = Signal(8)                       # tile mean, registered     (phase 2)
        self.comb += [
            prod.eq(s_r * mul),
            m_raw.eq(prod[18:]),
        ]
        b_old   = ram.rdata[0:16]               # 8.8
        m_old   = ram.rdata[16:24]
        b_int   = b_old[8:16]
        diff    = Signal((10, True))
        delta   = Signal(9)
        changed = Signal()
        self.comb += [
            diff.eq(m_r - b_int),
            delta.eq(Mux(diff < 0, -diff, diff)),
            changed.eq(delta > WATCH_THRESH),
        ]
        # background update B += ((m << 8) - B) >> a   (arithmetic shift)
        bdiff = Signal((18, True))
        b_new = Signal(16)
        self.comb += [
            bdiff.eq(Cat(C(0, 8), m_old) - b_old),
            b_new.eq(b_old + (bdiff >> a_shift)),
        ]
 
        # Each tile takes 4 clocks (timing: no long chain in one 54 MHz cycle). The RAM address is
        # held for all 4, so rdata stays valid from phase 1 on.
        #   BAND   ph0 address  ph1 s_r = sums[k]  ph2 m_r = mean  ph3 compare, store m, clear sum
        #   UPDATE ph0 address  ph1 b_r = B + (m - B) * alpha     ph2 store B   ph3 -
        ph   = Signal(2)
        b_r  = Signal(16)
        addr = Signal(len(ram.raddr))
        self.comb += [ram.raddr.eq(addr), ram.waddr.eq(addr)]
 
        self.fsm = fsm = FSM(reset_state="IDLE")
        band_req = Signal()                     # a band is complete and waits for its pass
        self.sync += If(band_end, band_req.eq(1)).Elif(fsm.ongoing("IDLE") & band_req, band_req.eq(0))
        fsm.act("IDLE",
            If(band_req,
                NextValue(k, 0), NextValue(ph, 0),
                NextValue(addr, pass_band * nx),
                NextState("BAND"),
            )
        )
        fsm.act("BAND",
            NextValue(ph, ph + 1),
            If(ph == 1, NextValue(s_r, sums[k])),
            If(ph == 2, NextValue(m_r, Mux(m_raw > 255, 255, m_raw))),
            If(ph == 3,
                clr.eq(1),
                ram.we.eq(1),
                ram.wdata.eq(Cat(b_old, m_r)),
                NextValue(k, k + 1),
                NextValue(addr, addr + 1),
                If(k == nx - 1, NextState("BANDEND")),
            ),
        )
        fsm.act("BANDEND",
            If(last, NextValue(k, 0), NextValue(ph, 0), NextValue(addr, 0), NextState("DECIDE"))
            .Else(NextState("IDLE")),
        )
        fsm.act("DECIDE",
            NextState("UPDATE"),
        )
        fsm.act("UPDATE",
            NextValue(ph, ph + 1),
            If(ph == 1, NextValue(b_r, b_new)),
            If(ph == 2,
                ram.we.eq(upd),
                ram.wdata.eq(Cat(b_r, m_old)),
            ),
            If(ph == 3,
                NextValue(k, k + 1),
                NextValue(addr, addr + 1),
                If(k == n_tiles - 1, NextState("IDLE")),
            ),
        )
 
        self.sync += If(fsm.ongoing("BAND") & (ph == 3) & changed,
            n_chg.eq(n_chg + 1),
            If((n_chg == 0) | (k < x0), x0.eq(k)),
            If((n_chg == 0) | (k > x1), x1.eq(k)),
            If(n_chg == 0, y0.eq(pass_band)),
            y1.eq(pass_band),
        )
 
        # DECIDE: Frigate's per-frame logic --------------------------------------------------------
        motion  = Signal()
        cal_nxt = Signal()
        self.comb += [
            motion.eq(n_chg >= WATCH_MIN_TILES),
            cal_nxt.eq((calibrating & ~(n_chg < cal_out)) | (n_chg > light)),
        ]
        self.sync += If(fsm.ongoing("DECIDE"),
            calibrating.eq(cal_nxt),
            a_shift.eq(Mux(cal_nxt, WATCH_ALPHA_CAL, WATCH_ALPHA)),
            self.status.fields.changed.eq(Mux(n_chg > 255, 255, n_chg)),
            # learning gate: motion frames are learned only after LEARN_AFTER in a row
            If(motion,
                If(motion_cnt != WATCH_LEARN_AFTER, motion_cnt.eq(motion_cnt + 1)),
                upd.eq(motion_cnt + 1 >= WATCH_LEARN_AFTER),
            ).Else(
                motion_cnt.eq(0),
                upd.eq(1),
            ),
            # episode / event
            If(motion & ~cal_nxt,
                off_cnt.eq(0),
                If(~active,
                    active.eq(1),
                    ready.eq(1),
                    If(ready & (lost != 15), lost.eq(lost + 1)),
                    ev_fid.eq(fid), ev_n.eq(n_chg),
                    ev_x0.eq(x0), ev_x1.eq(x1), ev_y0.eq(y0), ev_y1.eq(y1),
                ),
            ).Elif(active,
                If(off_cnt == WATCH_OFF_DELAY - 1, active.eq(0), off_cnt.eq(0)
                ).Else(off_cnt.eq(off_cnt + 1)),
            ),
            n_chg.eq(0),
        )
 
        # reading event1 takes the event; start / stop ------------------------------------------------
        self.sync += [
            If(self.event1.we, ready.eq(0)),
            If(start,
                running.eq(1), calibrating.eq(1), active.eq(0), off_cnt.eq(0),
                motion_cnt.eq(0), ready.eq(0), lost.eq(0), step.eq(WATCH_STEP - 1),
            ),
            If(stop, running.eq(0), active.eq(0)),
        ]
        self.comb += [
            self.status.fields.running.eq(running),
            self.status.fields.calibrating.eq(calibrating),
            self.status.fields.active.eq(active),
            self.status.fields.ready.eq(ready),
            self.status.fields.lost.eq(lost),
            self.event0.status.eq(Cat(ev_fid, ev_n)),
            self.event1.status.eq(Cat(ev_x0, ev_x1, ev_y0, ev_y1)),
        ]
 
 
