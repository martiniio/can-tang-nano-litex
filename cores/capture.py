"""
capture.py -- Capture: the M3 reads a full picture from the DVPFrontEnd pixel stream, at its own pace.

    fe.source --> Capture: 5-slot ring of self-describing row packets --> CSR --> M3 --> UART

The stream cannot be stalled (34 fps, ~27 Mpx/s) and a whole picture (480 KB) does not fit on the
chip, so Capture takes the picture row by row, from as many frames as needed: at the start of
every row, if this row is still missing for the current picture and a ring slot is free, the row is
claimed and written into that slot. Rows the M3 is too slow for are simply taken from a later
frame. A finished slot is a packet (32-bit words, little-endian bytes):

    word 0          'R' 'W' y_lo y_hi
    word 1          frame_id (bits 15:0) | picture_id (bits 23:16)
    words 2..W/4+1  pixels, 4 per word, byte 0 = leftmost
    word W/4+2      CRC-16/CCITT-FALSE (poly 0x1021, init 0xFFFF) of the W pixel bytes (bits 15:0)

The CRC is checked by the receiver: end to end over fabric, M3 and link.

Coverage: a table holding, per row, the picture_id it was last captured for -- starting a new
picture is just picture_id + 1, no clearing. A row is marked when its packet is complete.

Registers (CSR; the SoC adds the submodule name `cap` as prefix):
    cap_ctrl     start (pulse): begin a new picture (picture + 1, queue emptied)
                 stop  (pulse): end now, queue emptied
    cap_status   busy    (bit 0)      picture not fully delivered (capturing or queued)
                 level   (bits 4:1)   complete packets waiting in the queue (0..N_SLOTS)
                 picture (bits 15:8)  id of the current / last picture
                 rows    (bits 25:16) rows captured for this picture (done = height)
    cap_data     read = next word of the oldest packet; after its last word the packet is
                 removed from the queue. Read whole packets, only while level > 0.

Build constants (Capture.constants, published in soc.h by the SoC):
    CAP_WIDTH, CAP_HEIGHT, CAP_SLOTS, CAP_PACKET_WORDS

Memory: ring = 5 x (W/4 + 3) words of 32 bit (800 px: 1015 words -> 2 BSRAM), coverage =
height x 8 bit (1 BSRAM). Both use cap_sdp_ram (Verilog with syn_ramstyle="block_ram"): Gowin
turns Migen memories into flip-flops in this design.
"""

import os

from migen import *

from litex.gen import LiteXModule
from litex.soc.interconnect.csr import CSRStorage, CSRStatus, CSRField

N_SLOTS = 5     # 5 x 203 = 1015 words <= 1024: 2 BSRAM (Gowin splits 32-bit RAMs by width)

# Simple dual-port RAM (one write port, one registered read port, one clock) ---------------------

SDP_RAM_VERILOG = """\
// cap_sdp_ram.v -- simple dual-port block RAM (generated by cores/capture.py)
module cap_sdp_ram #(parameter W = 32, parameter AW = 11, parameter DEPTH = 2030) (
    input  wire          clk,
    input  wire          we,
    input  wire [AW-1:0] waddr,
    input  wire [W-1:0]  wdata,
    input  wire [AW-1:0] raddr,
    output reg  [W-1:0]  rdata
);
    reg [W-1:0] mem [0:DEPTH-1] /* synthesis syn_ramstyle = "block_ram" */;
    always @(posedge clk) begin
        if (we) mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end
endmodule
"""


class _SDPRam(Module):
    """we/waddr/wdata in, raddr in, rdata = mem[raddr] one clock later."""
    def __init__(self, platform, width, depth, gateware_dir, sim):
        aw = bits_for(depth - 1)
        self.we    = Signal()
        self.waddr = Signal(aw)
        self.wdata = Signal(width)
        self.raddr = Signal(aw)
        self.rdata = Signal(width)
        if sim:
            mem = Memory(width, depth)
            wp  = mem.get_port(write_capable=True)
            rp  = mem.get_port()
            self.specials += mem, wp, rp
            self.comb += [
                wp.we.eq(self.we), wp.adr.eq(self.waddr), wp.dat_w.eq(self.wdata),
                rp.adr.eq(self.raddr), self.rdata.eq(rp.dat_r),
            ]
        else:
            self.specials += Instance("cap_sdp_ram",
                p_W = width, p_AW = aw, p_DEPTH = depth,
                i_clk   = ClockSignal("sys"),
                i_we    = self.we,
                i_waddr = self.waddr,
                i_wdata = self.wdata,
                i_raddr = self.raddr,
                o_rdata = self.rdata,
            )
            os.makedirs(gateware_dir, exist_ok=True)
            path = os.path.join(gateware_dir, "cap_sdp_ram.v")
            with open(path, "w") as f:
                f.write(SDP_RAM_VERILOG)
            platform.add_source(path)


def crc16_ccitt_byte(crc, byte):
    """CRC-16/CCITT-FALSE, one byte, MSB first, as a Migen expression (8 unrolled bit steps)."""
    c = [crc[i] for i in range(16)]
    for i in reversed(range(8)):
        fb = c[15] ^ byte[i]
        c  = [fb] + c[:15]                                   # shift left, bit 0 <- feedback
        c  = [c[k] ^ fb if (0x1021 >> k) & 1 and k != 0 else c[k] for k in range(16)]
    return Cat(*c)


# Capture -------------------------------------------------------------------------------------------

class Capture(LiteXModule):
    """Full picture, row by row, from as many frames as needed, through a ring of row packets."""
    def __init__(self, platform, sink, width, height, gateware_dir, sim=False):
        assert width % 4 == 0
        wpr        = width // 4                  # pixel words per row
        slot_words = wpr + 3                     # header 2 + pixels + crc 1
        ring_words = N_SLOTS * slot_words

        # Registers ---------------------------------------------------------------------------------
        self.ctrl = CSRStorage(fields=[
            CSRField("start", size=1, offset=0, pulse=True, description="Start a new picture."),
            CSRField("stop",  size=1, offset=1, pulse=True, description="End now, empty the queue."),
        ])
        self.status = CSRStatus(fields=[
            CSRField("busy",       size=1,  offset=0),
            CSRField("level",      size=4,  offset=1),
            CSRField("picture",    size=8,  offset=8),
            CSRField("rows",       size=10, offset=16),
        ])
        self.data = CSRStatus(32, description="Next word of the oldest packet (read pops).")

        start = self.ctrl.fields.start
        stop  = self.ctrl.fields.stop

        # Memories ---------------------------------------------------------------------------------
        self.ring = ring = _SDPRam(platform, 32, ring_words, gateware_dir, sim)
        self.cov  = cov  = _SDPRam(platform, 8,  height,     gateware_dir, sim)

        # State -------------------------------------------------------------------------------------
        active     = Signal()                    # a picture is being captured
        picture_id = Signal(8)
        rows_done  = Signal(10)
        level      = Signal(4)                   # complete packets in the ring
        wr_base    = Signal(len(ring.waddr))     # slot being written (base address)
        rd_base    = Signal(len(ring.waddr))     # oldest packet (base address)
        rd_off     = Signal(max=slot_words)      # next word to read in it

        cap      = Signal()                      # a row is being captured into wr_base
        cap_y    = Signal(10)
        cap_fid  = Signal(16)
        pw       = Signal(24)                    # last 3 pixels (packing 4 -> 1 word)
        crc      = Signal(16)
        post     = Signal(2)                     # after the row: 1 crc, 2 header 0, 3 header 1

        def next_base(b):
            return Mux(b == ring_words - slot_words, 0, b + slot_words)

        # Coverage lookup: the next row's entry is read at every eol (rows are >= 1 blanking apart).
        self.sync += If(sink.valid & sink.eol,
            cov.raddr.eq(Mux(sink.eof, 0, sink.y + 1)),
        )
        missing = Signal()
        self.comb += missing.eq(cov.rdata != picture_id)

        # Pixel path ------------------------------------------------------------------------------
        first  = sink.valid & (sink.x == 0)
        claim  = Signal()
        commit = Signal()
        pop    = Signal()
        self.comb += [
            claim.eq(first & active & missing & (level < N_SLOTS) & (post == 0)),
            commit.eq(post == 3),
            pop.eq(self.data.we & (level != 0) & (rd_off == slot_words - 1)),
        ]

        crc_next = crc16_ccitt_byte(Mux(first, 0xFFFF, crc), sink.pix)
        word     = Cat(pw, sink.pix)            # 4th pixel arrives -> full word
        self.comb += [
            ring.we.eq(0),
            If(cap & sink.valid & (sink.x[0:2] == 3),
                ring.we.eq(1),
                ring.waddr.eq(wr_base + 2 + sink.x[2:]),
                ring.wdata.eq(word),
            ).Elif(post == 1,
                ring.we.eq(1), ring.waddr.eq(wr_base + slot_words - 1), ring.wdata.eq(crc),
            ).Elif(post == 2,
                ring.we.eq(1), ring.waddr.eq(wr_base),
                ring.wdata.eq(Cat(C(ord("R"), 8), C(ord("W"), 8), cap_y, C(0, 6))),
            ).Elif(post == 3,
                ring.we.eq(1), ring.waddr.eq(wr_base + 1),
                ring.wdata.eq(Cat(cap_fid, picture_id, C(0, 8))),
            ),
            # coverage: mark the row when its packet is complete
            cov.we.eq(commit),
            cov.waddr.eq(cap_y),
            cov.wdata.eq(picture_id),
        ]

        self.sync += [
            # capture a row
            If(sink.valid,
                pw.eq(Cat(pw[8:], sink.pix)),
                crc.eq(crc_next),
            ),
            If(first,
                cap.eq(claim),                    # a new row start also drops an unfinished row
                cap_y.eq(sink.y),
                cap_fid.eq(sink.frame_id),
            ).Elif(cap & sink.valid & sink.eol,
                cap.eq(0),
                post.eq(1),
            ),
            If(post != 0, post.eq(post + 1)),     # 1 -> 2 -> 3 -> 0
            If(commit,
                wr_base.eq(next_base(wr_base)),
                rows_done.eq(rows_done + 1),
            ),
            # read side
            If(self.data.we & (level != 0),
                If(rd_off == slot_words - 1,
                    rd_off.eq(0),
                    rd_base.eq(next_base(rd_base)),
                ).Else(
                    rd_off.eq(rd_off + 1),
                ),
            ),
            level.eq(level + commit - pop),
            # done: every row captured and read out
            If(active & (rows_done == height) & (level == 0) & ~cap & (post == 0),
                active.eq(0),
            ),
            # start / stop (last: they win)
            If(start | stop,
                active.eq(start),
                picture_id.eq(picture_id + start),
                rows_done.eq(0),
                level.eq(0),
                wr_base.eq(0), rd_base.eq(0), rd_off.eq(0),
                cap.eq(0), post.eq(0),
            ),
        ]
        self.comb += ring.raddr.eq(rd_base + rd_off)

        self.comb += [
            self.data.status.eq(ring.rdata),
            self.status.fields.busy.eq(active),
            self.status.fields.level.eq(level),
            self.status.fields.picture.eq(picture_id),
            self.status.fields.rows.eq(rows_done),
        ]

        # Sizes the firmware / receivers need; the SoC publishes them in soc.h.
        self.constants = {
            "CAP_WIDTH":        width,
            "CAP_HEIGHT":       height,
            "CAP_SLOTS":        N_SLOTS,
            "CAP_PACKET_WORDS": slot_words,
        }
